#!/usr/bin/env python3
"""Mirror pinned workspace inheritance without editing vendored manifests (Cargo #12154)."""
import argparse
from pathlib import Path
import re
import sys

from source import ROOT, baseline

BEGIN = "# BEGIN PINNED LITELLM WORKSPACE INHERITANCE"
END = "# END PINNED LITELLM WORKSPACE INHERITANCE"


def generate():
    config = baseline()
    vendor = config["destination"] + "/litellm-rust"
    upstream = (ROOT / vendor / "Cargo.toml").read_text()
    # Keep package metadata and dependency features byte for byte, adjusting only paths.
    section = upstream[upstream.index("[workspace.package]"):upstream.index("[profile.release]")].strip()
    section = section.replace('path = "crates/', f'path = "{vendor}/crates/')
    return f"{BEGIN}\n# Source: LiteLLM {config['version']} {config['commit']}; MIT, see vendor/litellm/LICENSE.\n# Generated by tools/parity/workspace.py. Upstream files remain unchanged.\n{section}\n{END}"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["generate", "check"])
    args = parser.parse_args()
    target = ROOT / "Cargo.toml"
    current = target.read_text()
    section = generate()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    expected = pattern.sub(lambda _: section, current) if BEGIN in current else current.rstrip() + "\n\n" + section + "\n"
    if args.action == "check":
        if current != expected:
            print("pinned workspace inheritance is stale", file=sys.stderr)
            return 1
    else:
        target.write_text(expected)
    return 0


if __name__ == "__main__":
    sys.exit(main())
